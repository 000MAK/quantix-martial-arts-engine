"""Render QMASE analysis outputs into a LaTeX technical report (optionally compiled to PDF).

Every number in the report is read from an analysis summary JSON written by this
engine; nothing is computed, rounded into a claim, or invented here. The report is
labelled exploratory and carries the dataset licence and attribution.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

_TEX_ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
                "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}

VICOS_CITATION = ("Hudovernik, V. and Sko\\v{c}aj, D. (2022). Video-Based Detection of Combat Positions and "
                  "Automatic Scoring in Jiu-jitsu. ACM Multimedia Workshop MMSports'22.")


def tex_escape(text: object) -> str:
    return "".join(_TEX_ESCAPES.get(c, c) for c in str(text))


def _num(value: object, digits: int = 2) -> str:
    if value is None:
        return "--"
    if isinstance(value, (int,)) and not isinstance(value, bool):
        return str(value)
    return f"{float(value):.{digits}f}"


def _p(value: object) -> str:
    """p-values keep two significant digits so small values never print as 0.00."""
    return "--" if value is None else f"{float(value):.2g}"


def _hawkes_section(s: dict) -> str:
    rows = []
    for label, m in s["models"].items():
        h, p = m["hawkes"], m["poisson"]
        rows.append(f"{tex_escape(label.replace('_', ' '))} & {_num(p['aic'], 1)} & {_num(h['aic'], 1)} & "
                    f"{_num(h['branching_ratio'], 3)} & {_num(h['excitation_timescale_s'], 1)} & "
                    f"{_p(p['ks_rescaled_p'])} & {_p(h['ks_rescaled_p'])} \\\\")
    return rf"""
\section{{Self-excitation of position changes (Hawkes process)}}
An exponential-kernel Hawkes intensity $\lambda(t)=\mu+n\beta\sum_{{t_i<t}}e^{{-\beta(t-t_i)}}$ was fitted by maximum
likelihood to {s['position_changes']} position changes over {_num(s['total_window_s'], 0)} s, and compared with a
constant-rate Poisson process. $n$ is the branching ratio. KS columns test time-rescaled intervals against Exp(1).

\begin{{table}}[h]\centering\small
\begin{{tabular}}{{lrrrrrr}}\toprule
Baseline & Poisson AIC & Hawkes AIC & $n$ & $1/\beta$ (s) & KS $p$ (Poisson) & KS $p$ (Hawkes)\\\midrule
{chr(10).join(rows)}
\bottomrule\end{{tabular}}
\caption{{Hawkes vs.\ Poisson fits. Primary model: {tex_escape(s['primary_model'].replace('_', ' '))}.}}
\end{{table}}

\noindent {tex_escape(s['model_note'])} {tex_escape(s['likelihood_ratio_note'])}
"""


def _semi_markov_section(s: dict) -> str:
    rows = []
    for label, m in s["dwell_models"].items():
        w = m["weibull"]
        lo, hi = w["shape_k_95ci_profile"]
        rows.append(f"{tex_escape(label.replace('_', ' '))} & {m['episodes_used']} & {m['observed_exits']} & "
                    f"{_num(m['exponential']['aic'], 1)} & {_num(w['aic'], 1)} & {_num(w['shape_k'])} & "
                    f"[{_num(lo)}, {_num(hi)}] & {_p(m['likelihood_ratio_p'])} \\\\")
    return rf"""
\section{{Dwell times (semi-Markov model)}}
Position episodes were fitted with censored exponential (memoryless) and Weibull dwell-time models; the first episode
of each session is excluded (unknown start) and the last is right-censored. The Weibull shape $k$ has a
profile-likelihood 95\% interval; $k>1$ means the hazard of leaving rises with time held.

\begin{{table}}[h]\centering\small
\begin{{tabular}}{{lrrrrrrr}}\toprule
Scale & Episodes & Exits & Exp.\ AIC & Weibull AIC & $k$ & 95\% CI & LR $p$\\\midrule
{chr(10).join(rows)}
\bottomrule\end{{tabular}}
\caption{{Dwell-time models. Primary model: {tex_escape(s['primary_model'].replace('_', ' '))}.}}
\end{{table}}

\noindent {tex_escape(s['interpretation_guide'])}
"""


def render_report(hawkes: dict | None, semi_markov: dict | None, title: str = "QMASE exploratory technical report") -> str:
    if hawkes is None and semi_markov is None:
        raise ValueError("At least one analysis summary is required")
    source = hawkes or semi_markov
    limitations = list(dict.fromkeys((hawkes or {}).get("limitations", []) + (semi_markov or {}).get("limitations", [])))
    items = "\n".join(rf"\item {tex_escape(x)}" for x in limitations)
    body = (_hawkes_section(hawkes) if hawkes else "") + (_semi_markov_section(semi_markov) if semi_markov else "")
    return rf"""\documentclass[11pt]{{article}}
\usepackage[T1]{{fontenc}}
\usepackage{{lmodern}}
\usepackage[margin=2.2cm]{{geometry}}
\usepackage{{booktabs,amsmath,hyperref}}
\title{{{tex_escape(title)}}}
\author{{Generated by quantix-martial-arts-engine}}
\date{{\today}}
\begin{{document}}
\maketitle
\begin{{abstract}}
Exploratory analysis of position-change timing in the ViCoS BJJ positions dataset. This is not a validated research
finding and is not generalizable beyond the sessions analysed. All values are read from the engine's analysis outputs.
\end{{abstract}}

\section{{Data and licence}}
Dataset: \texttt{{{tex_escape(source['dataset_id'])}}}, task \texttt{{{tex_escape(source['task'])}}}, licence
{tex_escape(source['license_id'])} (non-commercial, share-alike). Sessions used (one camera view each):
{tex_escape(', '.join(source['sessions_used']))}. Source: {VICOS_CITATION}
{body}
\section{{Limitations}}
\begin{{itemize}}
{items}
\end{{itemize}}
\end{{document}}
"""


def write_report(out_dir: Path, hawkes_json: Path | None, semi_markov_json: Path | None, compile_pdf: bool = True) -> dict:
    load = lambda p: json.loads(p.read_text(encoding="utf-8")) if p and p.exists() else None
    tex = render_report(load(hawkes_json), load(semi_markov_json))
    out_dir.mkdir(parents=True, exist_ok=True)
    tex_path = out_dir / "qmase_report.tex"
    tex_path.write_text(tex, encoding="utf-8")
    result = {"tex": str(tex_path), "pdf": None, "pdf_status": "not_requested"}
    if compile_pdf:
        engine = shutil.which("pdflatex")
        if engine is None:
            result["pdf_status"] = "pdflatex_not_found"
            return result
        for _ in range(2):  # second pass settles references
            proc = subprocess.run([engine, "-interaction=nonstopmode", "-halt-on-error", tex_path.name],
                                  cwd=out_dir, capture_output=True, text=True, timeout=300)
        pdf = out_dir / "qmase_report.pdf"
        result["pdf_status"] = "compiled" if proc.returncode == 0 and pdf.exists() else "compile_failed"
        result["pdf"] = str(pdf) if pdf.exists() else None
    return result
